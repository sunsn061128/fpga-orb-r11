"""Generate four-lane geometry and a proven bounded resize emission schedule."""
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FAST = ROOT / 'upstream/FPGA_ORB_HLS/fastv2'
spec = importlib.util.spec_from_file_location('profile', FAST / 'scripts/generate_profile_rom.py')
profile = importlib.util.module_from_spec(spec)
spec.loader.exec_module(profile)

def array(name, values, kind='uint32_t'):
    return f'static const {kind} {name}[{len(values)}] = {{\n' + profile.format_array(values, lambda v: str(v)+'u', 8) + '\n};\n'

def main():
    offsets, geometry = [], [[] for _ in range(4)]
    for w,h,b in zip(profile.WIDTHS, profile.HEIGHTS, profile.BUDGETS):
        g=profile.profile_geometry(w,h,b)
        info=profile.axis_info(w,g[0],g[2],g[4],g[6],g[7])
        offsets.append(len(geometry[0]))
        for x in range(0,w,4):
            for lane in range(4): geometry[lane].append(info[x+lane] if x+lane<w else 0)
    emit_offsets, valid, axes, tails = [], [], [[] for _ in range(4)], [[] for _ in range(4)]
    proofs=[]
    for level in range(7):
        sw,dw=profile.WIDTHS[level:level+2]
        emit_offsets.append(len(valid))
        group=0
        for x in range(0,sw,4):
            emit=group<dw//4 and profile.resize_axis(group*4+3,sw,dw)[1]<=min(x+3,sw-1)
            valid.append(int(emit))
            for lane in range(4):
                a,b,weight=profile.resize_axis(group*4+lane,sw,dw) if emit else (0,1,0)
                if emit: assert x-8<=a<b<=min(x+3,sw-1), (level,x,lane,a,b)
                axes[lane].append(a|(weight<<10))
            if emit:
                group+=1
                if group<dw//4: assert profile.resize_axis(group*4+3,sw,dw)[1]>min(x+3,sw-1)
        assert group==dw//4
        last=(sw-1)&~3
        for lane in range(4):
            a,b,weight=profile.resize_axis(group*4+lane,sw,dw) if lane<dw%4 else (0,1,0)
            if lane<dw%4: assert last-8<=a<b<=sw-1
            tails[lane].append(a|(weight<<10))
        proofs.append({'level':level,'input_quads':(sw+3)//4,'output_quads':(dw+3)//4,'tail_pixels':dw%4})
    text='#pragma once\n// Generated by scripts/generate_quad_rom.py; do not edit.\n#include <cstdint>\n'
    text+='#if defined(__SYNTHESIS__) || defined(FASTV2_HLS_CSIM)\n#include <ap_int.h>\ntypedef ap_uint<21> QuadAxis;\n#else\ntypedef uint32_t QuadAxis;\n#endif\nnamespace orb4_rom {\n'
    text+=array('kOffsets',offsets,'int')
    text+=array('kEmitOffsets',emit_offsets,'int')
    text+=array('kEmitValid',valid,'uint8_t')
    for lane in range(4):
        text+=array(f'kGeometry{lane}',geometry[lane])
        text+=array(f'kEmitAxis{lane}',axes[lane],'QuadAxis')
        text+=array(f'kTailAxis{lane}',tails[lane],'QuadAxis')
    text+='}\n'
    (FAST/'next/include/quad_rom.hpp').write_text(text,encoding='utf-8',newline='\n')
    import json
    (ROOT/'evidence/resize_schedule.json').write_text(json.dumps(proofs,indent=2)+'\n')
    print('QUAD_ROM_PASS all7 schedules, <=one full output quad/input quad, 12-sample windows')

if __name__=='__main__': main()

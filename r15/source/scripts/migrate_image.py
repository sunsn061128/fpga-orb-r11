"""Generate 2018.3 pragmas for unchanged score/reduction/writer arithmetic."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'upstream/FPGA_ORB_HLS/fastv2/next/src'
def pragmas(text):
    def bind(m):
        name,kind=m.groups()
        core={'ram_s2p':'RAM_S2P_BRAM','ram_t2p':'RAM_T2P_BRAM','fifo':'FIFO_BRAM'}[kind]
        return f'#pragma HLS RESOURCE variable={name} core={core}'
    text=re.sub(r'#pragma HLS BIND_STORAGE variable=(\w+) type=(\w+) impl=bram',bind,text)
    text=re.sub(r'#pragma HLS AGGREGATE variable=(\w+) compact=bit',r'#pragma HLS DATA_PACK variable=\1',text)
    text=re.sub(r' max_widen_bitwidth=64','',text)
    return text
def main():
    common=pragmas((SRC/'fastv2_hls.cpp').read_text())
    common=common.replace('#include "front2_axis_rom.hpp"','').replace('#include "front2_stream.hpp"','')
    # Only the fixed eight profiles reach this reducer; max budget is 217.
    common=common.replace('output_index < fastv2::kMaxSelected','output_index < 217')
    common=common.replace('    std::memcpy(result, words, sizeof(words));',
        '#pragma HLS ARRAY_PARTITION variable=words complete\n    std::memcpy(result, words, sizeof(words));')
    common=re.sub(r'(?m)^(    )hls::stream<([^>]+)> ([^&\n]+);$',r'\1static hls::stream<\2> \3;',common)
    (SRC/'common2018.hpp').write_text('// Generated by scripts/migrate_image.py.\n'+common,encoding='utf-8',newline='\n')
    image=(SRC/'layer2_images.hpp').read_text()
    first=image[:image.index('/** Odd-position virtual pairs')]
    writer=image[image.index('template<int Tag> void layer_write_words'):]
    front=(SRC/'front2_stream.hpp').read_text()
    reader=front[front.index('void read_front2_words'):front.index('/** One FIFO read')]
    (SRC/'image2018_helpers.hpp').write_text('// Generated by scripts/migrate_image.py.\n'+pragmas(first+reader+writer),encoding='utf-8',newline='\n')
    print('IMAGE_2018_PRAGMAS_GENERATED original FAST/reducer/writer arithmetic')
if __name__=='__main__':main()
